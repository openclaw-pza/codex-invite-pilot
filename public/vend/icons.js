// ---------- 品牌图标清单（simple-icons 自托管）----------
// 上面那十个是手写的多色图标（Google 四色、Microsoft 四格这种，单色版会失真）。
// 其余几百个走 scripts/build-service-icons.cjs 从 simple-icons 生成的
// Windows 保留设备名：CON / PRN / AUX / NUL / COM1-9 / LPT1-9。
// 带扩展名也照样保留（aux.svg 一样打不开），文件能被某些工具建出来，
// 但 git.exe、资源管理器、大部分 Win32 程序都读不了它 ——
// 实际后果是 `git add` 直接 fatal，整个仓库加不进去。
// 服务码里真的有一个 aux，所以这条不是理论问题。
// 规则：保留名后面缀一个 -，前后端用同一个函数算，别两边各写一份。
const WIN_RESERVED = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/i;
function safeIconName(code) {
  return WIN_RESERVED.test(code) ? `${code}-` : code;
}

// public/vend/icons/<服务码>.svg，清单在 service-icons.json。
//
// 为什么不把 SVG 内联进这个文件：几百条 path 大约 200KB+，会拖慢首屏；
// 拆成单文件走 <img> 可以被浏览器单独缓存、按需懒加载，和国旗是同一套路子。

let svcIconMap = null;
let svcIconPromise = null;

export async function loadServiceIcons() {
  if (svcIconMap) return svcIconMap;
  if (!svcIconPromise) {
    svcIconPromise = fetch('service-icons.json')
      .then((r) => (r.ok ? r.json() : {}))
      .then((data) => { svcIconMap = data || {}; return svcIconMap; })
      .catch(() => { svcIconMap = {}; return svcIconMap; });
  }
  return svcIconPromise;
}

// 首字母牌只在**确实没有**品牌图标时出现。
// 取字母时按「拉丁字母优先」——服务名常写成「Apple ID · 苹果」，
// 取到「苹」不如取到「A」认得快。
function fallbackLetter(code, name) {
  const text = String(name || code || '');
  const latin = text.replace(/[^A-Za-z0-9]/g, '');
  if (latin) return latin.slice(0, 1).toUpperCase();
  const cjk = text.replace(/[^一-龥]/g, '');
  if (cjk) return cjk.slice(0, 1);
  return String(code || '?').slice(0, 1).toUpperCase();
}

export function serviceIconHtml(code, name) {
  const layers = SERVICE_ICONS[code];
  if (layers) {
    const paths = layers.map(([d, fill]) => `<path d="${d}" fill="${fill}"></path>`).join('');
    return `<span class="svc-ico"><svg width="18" height="18" viewBox="0 0 24 24" aria-hidden="true">${paths}</svg></span>`;
  }
  if (svcIconMap && svcIconMap[code]) {
    return `<span class="svc-ico"><img src="icons/${encodeURIComponent(safeIconName(code))}.svg" width="18" height="18" alt="" loading="lazy" decoding="async"></span>`;
  }
  return `<span class="svc-ico svc-ico-text">${fallbackLetter(code, name)}</span>`;
}

// ---------- 国旗 ----------
// 用 flag-icons（MIT，官方 SVG）自托管，不手画、不用 emoji：
//   · emoji 国旗 Windows 不渲染，买家看到方框
//   · 手画的旗必然有画错的，挂错国旗比不挂旗糟得多
//
// country-iso.json 由 scripts/build-flags.cjs 从**上游真实国家清单**生成，
// 195 个国家全部映射到 ISO2（映射不上的会在构建时报出来，不会静默漏）。
// 上游加国家时重跑一次那个脚本即可。

let isoMap = null;
let isoMapPromise = null;

export async function loadIsoMap() {
  if (isoMap) return isoMap;
  if (!isoMapPromise) {
    isoMapPromise = fetch('country-iso.json')
      .then((r) => (r.ok ? r.json() : {}))
      .then((data) => { isoMap = data; return isoMap; })
      .catch(() => { isoMap = {}; return isoMap; });
  }
  return isoMapPromise;
}

// 国际区号：按国家 id 查构建期算好的真值。
// 不要用正则从号码里猜 —— 区号 1~4 位不定，贪婪匹配会把 +6391 当成菲律宾的区号
// （真实是 +63），买家照着填就永远收不到码。查不到就返回 null，让调用方整串显示。
export function callingCodeFor(countryId) {
  if (!isoMap) return null;
  return isoMap[String(countryId)]?.cc || null;
}

// 按上游的 country id 取，不靠名字模糊匹配 —— id 是不变量，名字会变
export function isoFor(region) {
  if (!isoMap) return null;
  const hit = isoMap[String(region?.id)];
  return hit ? hit.iso : null;
}

// 拿不到确定的 ISO 就给一个中性色块，看起来是刻意设计而不是缺图
export function flagHtml(region, { width = 30, height = 21 } = {}) {
  const iso = isoFor(region);
  if (!iso) {
    const label = (String(region?.englishName || region?.name || '').trim().slice(0, 2) || '·').toUpperCase();
    return `<span class="flag flag-blank" aria-hidden="true">${label}</span>`;
  }
  return `<span class="flag" aria-hidden="true"><img src="flags/${iso.toLowerCase()}.svg" width="${width}" height="${height}" alt="" loading="lazy" decoding="async"><span class="flag-edge"></span></span>`;
}
